/**
 * Classic Yarn v1 lockfile parser (cell c20).
 *
 * Yarn Berry (v2+) is detected and returned as unknown — this module does
 * not claim YAML/berry coverage. Indent grammar is recursive-descent, not a
 * regex stand-in for a full lockfile language.
 *
 * Never executes package scripts. Never fetches. Never follows symlinks.
 */

export const SCHEMA = "s127.c20.yarn-lock.parse.v1";
export const MAX_LOCKFILE_BYTES = 8 * 1024 * 1024;
export const MAX_LOCKFILE_LINES = 200_000;
export const MAX_ENTRIES = 80_000;

export const FORMATS = Object.freeze(["classic-v1", "berry", "unknown"]);

const HOSTILE_KEYS = new Set(["__proto__"]);

const BERRY_GENERATED =
  /^\s*#\s*This file is generated by running ["']yarn install["']/m;
const CLASSIC_HEADER = /^\s*#\s*yarn lockfile v1\s*$/m;
const METADATA_LINE = /^\s*__metadata:\s*$/m;
const CONFLICT_MARKER = /^(<<<<<<<|=======|>>>>>>>)/m;

/**
 * Classify lockfile text. Berry is a first-class unknown: do not feed it
 * to the classic parser (YAML `version:` would otherwise look like a value).
 */
export function stripBom(text) {
  if (typeof text !== "string" || text.length === 0) return text;
  if (text.charCodeAt(0) === 0xfeff) return text.slice(1);
  return text;
}

export function detectYarnLockFormat(text) {
  if (typeof text !== "string") {
    return {
      format: "unknown",
      reason: "not_text",
      coverage: "unknown",
      classicHeader: false,
      berry: false,
    };
  }
  text = stripBom(text);
  if (text.length === 0) {
    return {
      format: "unknown",
      reason: "empty",
      coverage: "unknown",
      classicHeader: false,
      berry: false,
    };
  }
  if (text.includes("\0")) {
    return {
      format: "unknown",
      reason: "nul_byte",
      coverage: "unknown",
      classicHeader: false,
      berry: false,
      hostile: true,
    };
  }
  if (CONFLICT_MARKER.test(text)) {
    return {
      format: "unknown",
      reason: "git_conflict_markers",
      coverage: "unknown",
      classicHeader: CLASSIC_HEADER.test(text),
      berry: false,
      hostile: true,
    };
  }

  const head = text.slice(0, 8192);
  const classicHeader = CLASSIC_HEADER.test(head);
  const metadata = METADATA_LINE.test(text.slice(0, 20000));
  const berryComment = BERRY_GENERATED.test(head);
  const hasResolution = /^\s+resolution:\s+/m.test(text.slice(0, 40000));
  const hasLinkType = /^\s+linkType:\s+/m.test(text.slice(0, 40000));
  const hasClassicResolved = /^\s+resolved\s+"/m.test(text);
  const hasClassicVersion = /^\s+version\s+"/m.test(text);

  if (metadata || (hasResolution && hasLinkType) || berryComment) {
    return {
      format: "berry",
      reason: metadata
        ? "metadata_block"
        : berryComment
          ? "berry_generated_comment"
          : "resolution_and_linkType",
      coverage: "unknown",
      classicHeader,
      berry: true,
      metadataVersion: readBerryMetadataVersion(text),
    };
  }

  if (classicHeader || (hasClassicResolved && hasClassicVersion)) {
    return {
      format: "classic-v1",
      reason: classicHeader ? "v1_header" : "classic_properties",
      coverage: "classic-v1-entries",
      classicHeader,
      berry: false,
    };
  }

  return {
    format: "unknown",
    reason: "unrecognized",
    coverage: "unknown",
    classicHeader: false,
    berry: false,
  };
}

function readBerryMetadataVersion(text) {
  const slice = text.slice(0, 4000);
  const m = slice.match(/__metadata:\s*\n(?:[ \t]+[^\n]*\n)*?[ \t]+version:\s*([0-9]+)/);
  return m ? Number(m[1]) : null;
}

export function tokenizeClassic(text) {
  const tokens = [];
  let i = 0;
  let line = 1;
  let col = 1;
  let atLineStart = true;
  let sawTabIndent = false;
  let unclosedQuote = false;

  const push = (type, value, startLine = line, startCol = col) => {
    tokens.push({ type, value, line: startLine, col: startCol });
  };

  while (i < text.length) {
    if (atLineStart) {
      atLineStart = false;
      const startCol = col;
      let spaces = 0;
      while (i < text.length && (text[i] === " " || text[i] === "\t")) {
        if (text[i] === "\t") sawTabIndent = true;
        spaces += 1;
        i += 1;
        col += 1;
      }
      if (spaces > 0) push("indent", spaces, line, startCol);
      continue;
    }

    const c = text[i];
    if (c === "\r") {
      i += 1;
      continue;
    }
    if (c === "\n") {
      push("newline", "\n");
      i += 1;
      line += 1;
      col = 1;
      atLineStart = true;
      continue;
    }
    if (c === " " || c === "\t") {
      i += 1;
      col += 1;
      continue;
    }
    if (c === "#") {
      const startCol = col;
      i += 1;
      col += 1;
      let body = "";
      while (i < text.length && text[i] !== "\n" && text[i] !== "\r") {
        body += text[i];
        i += 1;
        col += 1;
      }
      push("comment", body, line, startCol);
      continue;
    }
    if (c === ":") {
      push("colon", ":");
      i += 1;
      col += 1;
      continue;
    }
    if (c === ",") {
      push("comma", ",");
      i += 1;
      col += 1;
      continue;
    }
    if (c === '"') {
      const startLine = line;
      const startCol = col;
      i += 1;
      col += 1;
      let s = "";
      let closed = false;
      while (i < text.length) {
        const ch = text[i];
        if (ch === '"') {
          closed = true;
          i += 1;
          col += 1;
          break;
        }
        if (ch === "\\" && i + 1 < text.length) {
          const n = text[i + 1];
          const mapped = { n: "\n", r: "\r", t: "\t", '"': '"', "\\": "\\", "/": "/" };
          s += mapped[n] !== undefined ? mapped[n] : n;
          i += 2;
          col += 2;
          continue;
        }
        if (ch === "\n") break;
        s += ch;
        i += 1;
        col += 1;
      }
      if (!closed) {
        unclosedQuote = true;
        push("unclosed_quote", s, startLine, startCol);
        break;
      }
      push("string", s, startLine, startCol);
      continue;
    }

    const startCol = col;
    let s = "";
    while (i < text.length) {
      const ch = text[i];
      if (
        ch === " " ||
        ch === "\t" ||
        ch === "\n" ||
        ch === "\r" ||
        ch === ":" ||
        ch === "," ||
        ch === "#"
      ) {
        break;
      }
      s += ch;
      i += 1;
      col += 1;
    }
    if (s.length) {
      push("string", s, line, startCol);
    } else {
      push("invalid", c, line, startCol);
      i += 1;
      col += 1;
    }
  }

  push("eof", null);
  return { tokens, sawTabIndent, unclosedQuote };
}

class TokenCursor {
  constructor(tokens) {
    this.tokens = tokens;
    this.i = 0;
  }
  peek() {
    return this.tokens[this.i] || { type: "eof", value: null, line: 0, col: 0 };
  }
  peekType() {
    return this.peek().type;
  }
  next() {
    const tok = this.peek();
    if (tok.type !== "eof") this.i += 1;
    return tok;
  }
  skipIgnorable() {
    for (;;) {
      const t = this.peekType();
      if (t === "newline" || t === "comment") {
        this.next();
        continue;
      }
      if (t === "indent") {
        const n = this.tokens[this.i + 1];
        if (!n || n.type === "newline" || n.type === "comment" || n.type === "eof") {
          this.next();
          continue;
        }
      }
      break;
    }
  }
}

function currentIndent(cur) {
  if (cur.peekType() === "indent") return cur.peek().value;
  return 0;
}

function consumeOptionalIndent(cur) {
  if (cur.peekType() === "indent") return cur.next().value;
  return 0;
}

function parseString(cur, err) {
  const tok = cur.peek();
  if (tok.type !== "string") {
    throw err(`expected string, got ${tok.type}`, tok);
  }
  return cur.next().value;
}

function parseKeysAndMaybeValue(cur, err) {
  const keys = [parseString(cur, err)];
  while (cur.peekType() === "comma") {
    cur.next();
    keys.push(parseString(cur, err));
  }
  return keys;
}

function parseBlock(cur, minIndent, err, state) {
  const obj = Object.create(null);
  const entryOrder = [];

  while (cur.peekType() !== "eof") {
    cur.skipIgnorable();
    if (cur.peekType() === "eof") break;

    const indent = currentIndent(cur);
    if (indent <= minIndent) break;
    consumeOptionalIndent(cur);

    if (cur.peekType() === "comment" || cur.peekType() === "newline") continue;
    if (cur.peekType() === "eof") break;
    if (cur.peekType() !== "string") {
      throw err(`expected key, got ${cur.peekType()}`, cur.peek());
    }

    const keys = parseKeysAndMaybeValue(cur, err);
    let value;

    if (cur.peekType() === "colon") {
      cur.next();
      if (cur.peekType() === "string") {
        value = cur.next().value;
      } else {
        cur.skipIgnorable();
        const childIndent = currentIndent(cur);
        if (childIndent > indent) {
          value = parseBlock(cur, indent, err, state);
        } else {
          value = Object.create(null);
        }
      }
    } else if (cur.peekType() === "string") {
      value = cur.next().value;
    } else if (cur.peekType() === "newline" || cur.peekType() === "comment" || cur.peekType() === "eof") {
      value = Object.create(null);
    } else {
      throw err(`expected value after ${keys.join(", ")}, got ${cur.peekType()}`, cur.peek());
    }

    for (const key of keys) {
      if (isHostileKey(key)) {
        state.issues.push({
          kind: "hostile_key",
          key,
          line: cur.peek().line,
        });
        continue;
      }
      if (Object.prototype.hasOwnProperty.call(obj, key) && obj[key] !== value) {
        state.issues.push({
          kind: "duplicate_key",
          key,
          line: cur.peek().line,
        });
      }
      obj[key] = value;
    }

    if (minIndent < 0) {
      entryOrder.push({ keys, value });
    }
  }

  if (minIndent < 0) obj.__entries = entryOrder;
  return obj;
}

function isHostileKey(key) {
  if (HOSTILE_KEYS.has(key)) return true;
  const name = key.startsWith("@")
    ? key.slice(0, Math.max(0, key.indexOf("@", 1)))
    : key.split("@")[0];
  return HOSTILE_KEYS.has(name);
}

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function entryFields(value) {
  if (!isPlainObject(value)) {
    return { version: null, resolved: null, integrity: null, dependencies: null, extra: {} };
  }
  const extra = {};
  for (const [k, v] of Object.entries(value)) {
    if (k === "version" || k === "resolved" || k === "integrity" || k === "dependencies" || k === "optionalDependencies") {
      continue;
    }
    extra[k] = v;
  }
  return {
    version: typeof value.version === "string" ? value.version : null,
    resolved: typeof value.resolved === "string" ? value.resolved : null,
    integrity: typeof value.integrity === "string" ? value.integrity : null,
    dependencies: isPlainObject(value.dependencies) ? { ...value.dependencies } : null,
    optionalDependencies: isPlainObject(value.optionalDependencies)
      ? { ...value.optionalDependencies }
      : null,
    extra,
  };
}

/**
 * Parse classic yarn.lock text. Berry/unknown formats return ok:false
 * with coverage "unknown" and do not invent entries.
 */
export function parseYarnLock(text, options = {}) {
  const limitations = [
    "classic yarn.lock v1 grammar only",
    "yarn berry (v2+) is unsupported and stays unknown",
    "no package-manager execution; no registry fetch",
  ];

  if (typeof text !== "string") {
    return failParse("not_text", { limitations });
  }
  text = stripBom(text);
  if (Buffer.byteLength(text, "utf8") > (options.maxBytes || MAX_LOCKFILE_BYTES)) {
    return failParse("oversize", { limitations, hostile: true });
  }
  const lineCount = countLines(text);
  if (lineCount > (options.maxLines || MAX_LOCKFILE_LINES)) {
    return failParse("too_many_lines", { limitations, hostile: true });
  }

  const detection = detectYarnLockFormat(text);
  if (detection.format === "berry") {
    return {
      ok: false,
      schema: SCHEMA,
      format: "berry",
      coverage: "unknown",
      reason: "yarn_berry_unsupported",
      detection,
      object: null,
      entries: [],
      issues: [{ kind: "berry_unsupported", detail: detection.reason }],
      limitations: [
        ...limitations,
        `yarn berry lockfile (${detection.reason}); resolved versions unknown`,
      ],
      unknownReasons: ["yarn_berry_unsupported"],
    };
  }
  if (detection.format !== "classic-v1") {
    return {
      ok: false,
      schema: SCHEMA,
      format: detection.format,
      coverage: "unknown",
      reason: detection.reason,
      detection,
      object: null,
      entries: [],
      issues: [{ kind: "unrecognized_lockfile", detail: detection.reason }],
      limitations: [...limitations, `lockfile format ${detection.reason}`],
      unknownReasons: [`yarn_lock_format_${detection.reason}`],
    };
  }

  const { tokens, sawTabIndent, unclosedQuote } = tokenizeClassic(text);
  if (unclosedQuote) {
    return failParse("unclosed_quote", { limitations, detection, format: "classic-v1" });
  }
  if (tokens.some((t) => t.type === "invalid")) {
    const bad = tokens.find((t) => t.type === "invalid");
    return failParse("invalid_token", {
      limitations,
      detection,
      format: "classic-v1",
      line: bad?.line,
    });
  }

  const state = { issues: [] };
  const cur = new TokenCursor(tokens);
  let object;
  try {
    object = parseBlock(cur, -1, parseError, state);
    cur.skipIgnorable();
    if (cur.peekType() !== "eof") {
      return failParse("trailing_tokens", {
        limitations,
        detection,
        format: "classic-v1",
        line: cur.peek().line,
      });
    }
  } catch (error) {
    return failParse(error.code || "parse_error", {
      limitations,
      detection,
      format: "classic-v1",
      line: error.line,
      message: error.message,
    });
  }

  const rawEntries = Array.isArray(object.__entries) ? object.__entries : [];
  delete object.__entries;
  if (rawEntries.length > (options.maxEntries || MAX_ENTRIES)) {
    return failParse("too_many_entries", { limitations, detection, format: "classic-v1" });
  }

  const entries = [];
  const seen = new Set();
  for (const row of rawEntries) {
    const fields = entryFields(row.value);
    const keys = row.keys.filter((k) => !HOSTILE_KEYS.has(k));
    if (!keys.length) continue;
    const sig = `${keys.slice().sort().join("\0")}@${fields.version}@${fields.resolved}`;
    if (seen.has(sig)) continue;
    seen.add(sig);
    entries.push({
      keys,
      version: fields.version,
      resolved: fields.resolved,
      integrity: fields.integrity,
      dependencies: fields.dependencies,
      optionalDependencies: fields.optionalDependencies,
    });
  }

  if (sawTabIndent) {
    limitations.push("tab indentation seen; classic yarn.lock is 2-space");
  }
  if (!detection.classicHeader) {
    limitations.push("missing `# yarn lockfile v1` header; classified via classic properties");
  }

  const missingVersion = entries.filter((e) => !e.version).length;
  if (missingVersion) {
    state.issues.push({ kind: "missing_version_field", count: missingVersion });
  }

  return {
    ok: true,
    schema: SCHEMA,
    format: "classic-v1",
    coverage: "classic-v1-entries",
    reason: null,
    detection,
    object,
    entries,
    issues: state.issues,
    limitations,
    unknownReasons: [],
    sawTabIndent,
    entryCount: entries.length,
  };
}

function countLines(text) {
  if (!text) return 0;
  let n = 1;
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] === "\n") n += 1;
  }
  return n;
}

function parseError(message, tok) {
  const err = new Error(message);
  err.code = "parse_error";
  err.line = tok?.line ?? null;
  err.col = tok?.col ?? null;
  return err;
}

function failParse(reason, extra = {}) {
  return {
    ok: false,
    schema: SCHEMA,
    format: extra.format || "unknown",
    coverage: "unknown",
    reason,
    detection: extra.detection || null,
    object: null,
    entries: [],
    issues: [{ kind: reason, line: extra.line ?? null, message: extra.message ?? null }],
    limitations: extra.limitations || [],
    unknownReasons: [`yarn_lock_${reason}`],
    hostile: extra.hostile === true,
  };
}
